import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

test('site estático persiste recursos de abas, executa e exporta sem API', async ({ page, context }) => {
  const apiRequests = [];
  page.on('request', request => { if (new URL(request.url()).pathname.includes('/api/')) apiRequests.push(request.url()); });
  await page.goto('./');
  await expect(page.locator('.brand-logo')).toBeVisible();
  expect(await page.locator('.brand-logo').evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true);
  await page.getByRole('button', { name: 'Mostrar editor', exact: true }).click();
  const pixels = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = c.height = 4; c.getContext('2d').fillStyle = '#ff0000'; c.getContext('2d').fillRect(0, 0, 4, 4); return c.toDataURL().split(',')[1]; });
  await page.locator('input[type=file][multiple]').setInputFiles({ name: 'persistida.png', mimeType: 'image/png', buffer: Buffer.from(pixels, 'base64') });
  await expect(page.locator('.resource-info').getByText('persistida.png', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('.resource-info').getByText('persistida.png', { exact: true })).toBeVisible();
  await page.locator('.cm-content').fill('programa { inclua biblioteca Graficos --> g funcao inicio() { g.iniciar_modo_grafico() inteiro i = g.carregar_imagem("persistida.png") g.desenhar_imagem(0, 0, i) g.renderizar() escreva("Sem API") } }');
  await page.getByRole('button', { name: 'Executar programa', exact: true }).click();
  await expect(page.getByLabel('Terminal de execução')).toContainText('Sem API');
  expect(await page.locator('canvas').evaluate(c => Array.from(c.getContext('2d').getImageData(0, 0, 1, 1).data))).toEqual([255, 0, 0, 255]);
  await page.getByRole('button', { name: 'Exportar projeto', exact: true }).click();
  await expect(page.getByText('HTML independente', { exact: true })).toBeVisible();
  const pending = page.waitForEvent('download');
  await page.getByRole('dialog', { name: 'Exportar projeto' }).getByRole('button', { name: 'Exportar projeto', exact: true }).click();
  const file = path.resolve('test-results/export-estatico.html');
  await (await pending).saveAs(file);
  expect(await readFile(file, 'utf8')).not.toContain('/api/');
  const player = await context.newPage();
  await player.goto(pathToFileURL(file).href);
  await player.getByRole('button', { name: 'Executar', exact: true }).click();
  await expect(player.getByLabel('Console')).toContainText('Sem API');
  await player.close();
  await page.getByRole('button', { name: 'Fechar exportação' }).click();
  await page.getByRole('button', { name: 'Abrir ajuda', exact: true }).click();
  await expect(page.frameLocator('.help-reader iframe').getByRole('heading', { name: 'Linguagem Portugol', exact: true })).toBeVisible();
  await expect(page.frameLocator('.help-reader iframe').locator('pre')).toBeVisible();
  expect(apiRequests).toEqual([]);
});
